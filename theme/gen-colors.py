#!/usr/bin/env python3
"""Writes logic-colors.h: Logic catalog color names that have one appearance."""
import collections, glob, json, subprocess, sys

APP = '/Applications/Logic Pro.app/Contents'

def main():
   appearances = collections.defaultdict(set)
   paths = glob.glob(f'{APP}/Frameworks/*.framework/Versions/A/Resources/*.car') + [ f'{APP}/Resources/Assets.car' ]
   for path in paths:
      info = json.loads(subprocess.run([ 'xcrun', 'assetutil', '--info', path ], capture_output=True, text=True).stdout)
      for item in info[1:]:
         if item.get('AssetType') == 'Color':
            appearances[item['Name']].add(item.get('Appearance') or 'any')
   names = sorted(name for name, seen in appearances.items() if len(seen) == 1)
   with open(sys.argv[1], 'w') as out:
      out.write('// Generated by gen-colors.py.\nstatic const char *SINGLE_APPEARANCE_COLORS[] = {\n')
      out.writelines(f'   {json.dumps(name)},\n' for name in names)
      out.write('};\n')
   print(f'{len(names)} of {len(appearances)} color names have one appearance')

main()
